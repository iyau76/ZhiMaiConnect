import { useSyncExternalStore } from "react";

export type Lang = "zh" | "en";

const LANG_KEY = "openglass.lang";

let current: Lang = "zh";
const listeners = new Set<() => void>();

function syncDocumentLang() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = current === "zh" ? "zh-CN" : "en";
  document.title =
    current === "zh"
      ? "知脉 Connect · 人际关系记忆与行动助手"
      : "Zhimai Connect · Relationship Memory & Action Assistant";
  const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
  if (description) {
    description.content =
      current === "zh"
        ? "本地优先、证据可追溯的人际关系记忆与行动助手。"
        : "A local-first, evidence-traceable relationship memory and action assistant.";
  }
}

export function initLang() {
  try {
    const stored = localStorage.getItem(LANG_KEY) as Lang | null;
    if (stored === "zh" || stored === "en") current = stored;
  } catch {
    /* ignore */
  }
  syncDocumentLang();
  listeners.forEach((fn) => fn());
}

export function setLang(lang: Lang) {
  current = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* ignore */
  }
  syncDocumentLang();
  listeners.forEach((fn) => fn());
}

export function getLang(): Lang {
  return current;
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (cb) => {
      listeners.add(cb);
      return () => listeners.delete(cb);
    },
    () => current,
    () => "zh" as Lang,
  );
}

